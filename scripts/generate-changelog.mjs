#!/usr/bin/env node
// Generates changelog entries from merged-PR titles (conventional commits
// format) since the last release tag, for the "Release-vX.Y.Z" release
// workflow. Not meant to be run outside CI, but safe to run locally:
//   node scripts/generate-changelog.mjs <version> [previousTag]
import { execFileSync } from "node:child_process";
import { readFileSync, writeFileSync, existsSync } from "node:fs";

const RECORD_SEP = "\x1e";
const RELEASE_TITLE_RE = /^Release-v\d+\.\d+\.\d+$/i;
const TITLE_RE = /^(\w+)(\([\w.\-/ ]+\))?(!)?:\s*(.+)$/;

// type -> [heading, includeInUserFacing]
const TYPE_INFO = {
  feat: ["Features", true],
  fix: ["Bug Fixes", true],
  perf: ["Performance Improvements", true],
  revert: ["Reverts", true],
  docs: ["Documentation", false],
  style: ["Styles", false],
  refactor: ["Refactoring", false],
  test: ["Tests", false],
  build: ["Build System", false],
  ci: ["CI/CD", false],
  chore: ["Chores", false],
};
const OTHER_HEADING = "Other Changes";

function git(args) {
  return execFileSync("git", args, { encoding: "utf8" });
}

function getMergedPrTitles(previousTag) {
  const range = previousTag ? `${previousTag}..HEAD` : "HEAD";
  const log = git([
    "log",
    range,
    "--merges",
    `--format=%b${RECORD_SEP}`,
  ]);
  return log
    .split(RECORD_SEP)
    .map((block) => block.trim().split("\n")[0]?.trim())
    .filter((title) => title && !RELEASE_TITLE_RE.test(title));
}

function categorize(titles) {
  const buckets = new Map(); // heading -> { userFacing, entries: [] }
  const breaking = [];
  const other = [];

  for (const title of titles) {
    const match = TITLE_RE.exec(title);
    if (!match) {
      other.push(title);
      continue;
    }
    const [, type, , bang, description] = match;
    const info = TYPE_INFO[type.toLowerCase()];
    if (bang) breaking.push(description);
    if (!info) {
      other.push(title);
      continue;
    }
    const [heading, userFacing] = info;
    if (!buckets.has(heading)) buckets.set(heading, { userFacing, entries: [] });
    buckets.get(heading).entries.push(description);
  }

  return { buckets, breaking, other };
}

function renderSection({ buckets, breaking, other }, { userFacingOnly }) {
  const lines = [];

  if (breaking.length) {
    lines.push("### ⚠ BREAKING CHANGES", "");
    for (const entry of breaking) lines.push(`- ${entry}`);
    lines.push("");
  }

  for (const [heading, { userFacing, entries }] of buckets) {
    if (userFacingOnly && !userFacing) continue;
    lines.push(`### ${heading}`, "");
    for (const entry of entries) lines.push(`- ${entry}`);
    lines.push("");
  }

  if (!userFacingOnly && other.length) {
    lines.push(`### ${OTHER_HEADING}`, "");
    for (const entry of other) lines.push(`- ${entry}`);
    lines.push("");
  }

  if (!lines.length) lines.push("No notable changes.", "");
  return lines.join("\n").trim();
}

function prependToChangelog(path, header, version, date, section) {
  const entry = `## [${version}] - ${date}\n\n${section}\n`;

  // Keep any prior version entries (anything from the first "## [" heading
  // onward); always rewrite the header/preamble fresh, so this works
  // whether the file was hand-seeded or previously generated by this script.
  let priorEntries = "";
  if (existsSync(path)) {
    const existing = readFileSync(path, "utf8");
    const idx = existing.search(/^## \[/m);
    if (idx !== -1) priorEntries = existing.slice(idx);
  }

  const body = priorEntries ? `${entry}\n${priorEntries}` : entry;
  writeFileSync(path, `${header}\n\n${body}`.trimEnd() + "\n");
}

function bumpPackageVersion(version) {
  const path = "package.json";
  const content = readFileSync(path, "utf8");
  const updated = content.replace(
    /^(\s*"version"\s*:\s*")[^"]*(")/m,
    `$1${version}$2`
  );
  writeFileSync(path, updated);
}

function main() {
  const [, , version, previousTag] = process.argv;
  if (!version) {
    console.error("Usage: generate-changelog.mjs <version> [previousTag]");
    process.exit(1);
  }

  const titles = getMergedPrTitles(previousTag || "");
  const categorized = categorize(titles);
  const date = new Date().toISOString().slice(0, 10);

  const userSection = renderSection(categorized, { userFacingOnly: true });
  const devSection = renderSection(categorized, { userFacingOnly: false });

  prependToChangelog(
    "CHANGELOG.md",
    "# Changelog\n\nUser-facing changes to the currency converter API. See [CHANGELOG-DEV.md](./CHANGELOG-DEV.md) for the full contributor changelog.",
    version,
    date,
    userSection
  );
  prependToChangelog(
    "CHANGELOG-DEV.md",
    "# Developer Changelog\n\nFull changelog for contributors, including internal/tooling changes not listed in [CHANGELOG.md](./CHANGELOG.md).",
    version,
    date,
    devSection
  );

  bumpPackageVersion(version);

  // Release notes body (user-facing section) for `gh release create --notes-file`.
  writeFileSync("/tmp/release-notes.md", userSection + "\n");

  console.log(`Generated changelog for v${version} from ${titles.length} merged PR(s).`);
}

main();
